def test_fuzzy_recall_only_proposes_candidates() -> None:
    subjects = pd.DataFrame(
        [
            {"cgedq_person_id": "N1", "name_norm": "張廷玉", "native_province": "安徽", "degree_effective": "進士"},
            {"cgedq_person_id": "N2", "name_norm": "完全不像", "native_province": None, "degree_effective": None},
        ]
    )
    candidates = pd.DataFrame(
        [
            {"cbdb_personid": 10, "name_norm": "張廷玉", "cbdb_province": "安徽", "degree_cbdb": "進士"},
            {"cbdb_personid": 11, "name_norm": "張廷玉", "cbdb_province": "江蘇", "degree_cbdb": None},
        ]
    )
    recall = recall_candidates(subjects, candidates, config=RecallConfig(limit=3, score_cutoff=82.0))
    assert set(recall["match_status"]) == {CANDIDATE_STATUS}
    assert "accepted" not in set(recall["match_status"])
    assert set(recall["subject_id"]) == {"N1"}  # the unrelated subject gets no proposal
    assert len(recall) == 2  # both same-name candidates survive
    assert "province=match" in recall.set_index("candidate_cbdb_personid").at[10, "match_features"]
    assert recall["match_score"].min() == 100.0
