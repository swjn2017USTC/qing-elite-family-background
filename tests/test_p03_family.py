# --------------------------------------------------------------- cost model


def test_cost_estimate_follows_published_prices() -> None:
    estimate = estimate_tokens(
        1000,
        [1000] * 10,
        output_template="x" * 500,
        tokens_per_char=0.6,
        prompt_overhead_tokens=400,
    )
    # 1000 chars x 0.6 + 400 overhead = 1000 input tokens per person
    assert estimate.mean_input_tokens == 1000.0
    assert estimate.total_input_tokens == 1_000_000.0
    assert estimate.total_output_tokens == 300_000.0
    off_peak = PRICES_CNY_PER_MTOK["off_peak"]
    expected = 1.0 * off_peak["input_cache_miss"] + 0.3 * off_peak["output"]
    assert estimate.rmb_off_peak == pytest.approx(round(expected, 2))
    assert estimate.rmb_peak > estimate.rmb_off_peak


