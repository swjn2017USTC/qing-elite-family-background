# --------------------------------------------------------------- kinship slots


def test_slot_codes_cover_variants_but_prefer_the_primary_code() -> None:
    assert _slot_for_code(75) == "father"
    assert _slot_for_code(82) == "father"  # 嗣父 is still a father slot
    assert _slot_for_code(62) == "grandfather"
    assert _slot_for_code(48) == "great_grandfather"
    assert _slot_for_code(180) is None  # 子 is not an ancestor slot
    assert _code_rank("father", 75) < _code_rank("father", 82)


def test_merged_person_ids_are_rewritten_to_the_survivor() -> None:
    merged = {98561: 31}
    assert _rewrite_id(98561, merged) == 31
    assert _rewrite_id(42, merged) == 42
    assert _rewrite_id(None, merged) is None


def test_evidence_origin_separates_cited_from_autogenerated() -> None:
    assert _evidence_origin(4763, None) == "source_cited"
    assert _evidence_origin(0, "Auto-generated from PersonID = 1") == "autogenerated_only"
    assert _evidence_origin(0, None) == "unattributed"
    assert _evidence_origin(12, "auto") == "source_cited_autogenerated"


